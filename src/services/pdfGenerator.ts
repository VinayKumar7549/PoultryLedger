/**
 * Creates base jsPDF instance configured for A4 Portrait with 15mm margins
 */
function createBasePdf(): jsPDF {
  return new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  })
}

/**
 * Standard Minimalist Black & White Header (15mm margin boundary)
 * Printable width: 180mm (210mm - 30mm)
 */
function drawHeader(
  doc: jsPDF,
  profile: BusinessProfile,
  reportTitle: string,
  genDateStr: string
): number {
  const pageWidth = doc.internal.pageSize.width || 210

  // Business Name (Bold, Black, 14pt)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(14)
  doc.setTextColor(0, 0, 0)
  doc.text((profile.businessName || 'POULTRY LEDGER').toUpperCase(), 15, 15)

  // Report Title (Right Aligned, Bold, 12pt)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(12)
  doc.setTextColor(0, 0, 0)
  doc.text(reportTitle.toUpperCase(), pageWidth - 15, 15, { align: 'right' })

  // Business Subtitle / Contact Details
  const contactLines: string[] = []
  if (profile.ownerName) contactLines.push(`Prop: ${profile.ownerName}`)
  if (profile.phoneNumber) contactLines.push(`Phone: ${profile.phoneNumber}`)
  if (profile.address) contactLines.push(`Address: ${profile.address}`)
  const contactStr = contactLines.length > 0 ? contactLines.join('  |  ') : ''

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  doc.setTextColor(50, 50, 50)
  if (contactStr) {
    doc.text(contactStr, 15, 20)
  }

  doc.text(`Generation Date: ${genDateStr}`, pageWidth - 15, 20, { align: 'right' })

  // Thin Black Divider Rule (15mm to 195mm)
  doc.setDrawColor(0, 0, 0)
  doc.setLineWidth(0.2)
  doc.line(15, 23, pageWidth - 15, 23)

  return 26
}

/**
 * Attaches repeating page footer: "Generated by PoultryLedger" and "Page X of Y"
 */
function attachFooter(doc: jsPDF) {
  const pageCount = (doc as any).internal.getNumberOfPages()
  const pageWidth = doc.internal.pageSize.width || 210
  const pageHeight = doc.internal.pageSize.height || 297

  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)
    doc.setDrawColor(0, 0, 0)
    doc.setLineWidth(0.2)
    doc.line(15, pageHeight - 12, pageWidth - 15, pageHeight - 12)

    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8)
    doc.setTextColor(50, 50, 50)
    doc.text('Generated by PoultryLedger', 15, pageHeight - 6)
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - 15, pageHeight - 6, { align: 'right' })
  }
}

